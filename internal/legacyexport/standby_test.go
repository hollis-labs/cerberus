// copyDir copies a fixture directory (files 0600, directories 0700).
func copyDir(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.WalkDir(src, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		if d.IsDir() {
			return os.MkdirAll(filepath.Join(dst, rel), 0o700)
		}
		data, err := os.ReadFile(p) //nolint:gosec // the fixture
		if err != nil {
			return err
		}
		return os.WriteFile(filepath.Join(dst, rel), data, 0o600) //nolint:gosec // the test's own dir
	})
	if err != nil {
		t.Fatal(err)
	}
}

// standbySetup is a data directory whose main key is the old-tree fixture's (as migrate-from
// leaves it) and the standby.d archive main's writers produced (testdata/standby, generated by
// testdata/standby_gen_on_main.go.txt).
func standbySetup(t *testing.T) (archive, data string) {
	t.Helper()
	root := t.TempDir()
	t.Cleanup(func() { // the sidecar is read-only; let the temp dir go
		_ = filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
			if err == nil && d.IsDir() {
				_ = os.Chmod(p, 0o700) //nolint:gosec // the test's own dir
			}
			return nil
		})
	})
	archive, data = filepath.Join(root, "archive", "standby.d"), filepath.Join(root, "data")
	copyDir(t, filepath.Join("testdata", "standby", "standby.d"), archive)
	copyDir(t, filepath.Join(legacyimporttest.Testdata(), "oldtree", "audit"), filepath.Join(data, "audit"))
	return archive, data
}

func archiveFingerprint(t *testing.T, archive string) string {
	t.Helper()
	fp, err := legacyimport.TakeFingerprint(archive, filepath.Join(archive, "no-db"))
	if err != nil {
		t.Fatal(err)
	}
	return fp.Digest
}

// The sidecar import: a read-only copy, every source file hashed and the source untouched, the
// chain checked with no anchor, each standby verb's digest attributed to the key it was made
// with (both keys accepted), sessions.json parsed, and the report written beside the copy.
func TestImportStandby(t *testing.T) {
	archive, data := standbySetup(t)
	before := archiveFingerprint(t, archive)
	r, err := ImportStandby(StandbyOptions{From: archive, DataDir: data})
	if err != nil {
		t.Fatalf("import-standby: %v %v", err, r.Refusals)
	}
	if r.Result != "imported" || !r.SourceUnchanged || len(r.SourceFiles) != 4 || archiveFingerprint(t, archive) != before {
		t.Fatalf("result %s, source unchanged %v, %d files", r.Result, r.SourceUnchanged, len(r.SourceFiles))
	}
	if r.Chain.Verify != "ok" || r.Chain.Records != 8 || r.Chain.Anchored {
		t.Fatalf("chain %+v", r.Chain)
	}
	if r.Keys.Same || r.Keys.MainFingerprint == "" || r.Keys.StandbyFingerprint == "" {
		t.Fatalf("keys %+v", r.Keys)
	}
	got := map[string]string{}
	for _, v := range r.Verbs {
		if v.Resource != "web" {
			t.Errorf("verb %+v", v)
		}
		got[v.Operation+"/"+v.Kind] = v.Match
	}
	want := map[string]string{"apply/intent": MatchStandby, "apply/outcome": MatchStandby, "stop/intent": MatchMain, "stop/outcome": MatchMain,
		"reload/intent": MatchNeither, "reload/outcome": MatchNeither}
	if !reflect.DeepEqual(got, want) || r.Matches[MatchMain] != 2 || r.Matches[MatchStandby] != 2 || r.Matches[MatchNeither] != 2 {
		t.Fatalf("matches %v (%v), want %v", got, r.Matches, want)
	}
	if r.Sessions == nil || !reflect.DeepEqual(r.Sessions.IDs, []string{"web", "api"}) {
		t.Fatalf("sessions %+v", r.Sessions)
	}

	target := filepath.Join(data, filepath.FromSlash(SidecarStandbyRel))
	err = filepath.WalkDir(target, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		fi, _ := d.Info()
		want := os.FileMode(sidecarFileMode)
		if d.IsDir() {
			want = sidecarDirMode
		}
		if fi.Mode().Perm() != want {
			t.Errorf("%s mode %v, want %v", p, fi.Mode().Perm(), want)
		}
		return nil
	})
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range r.SourceFiles {
		if b, _ := os.ReadFile(filepath.Join(target, f.Path)); string(b) != string(readBytes(t, filepath.Join(archive, f.Path))) { //nolint:gosec // the test's own dir
			t.Errorf("%s differs in the sidecar", f.Path)
		}
	}
	var saved StandbyReport
	if err := json.Unmarshal(readBytes(t, filepath.Join(target, StandbyReportName)), &saved); err != nil || saved.Result != "imported" || len(saved.Verbs) != 6 {
		t.Fatalf("import-report.json: %+v %v", saved, err)
	}
	if _, err := os.Stat(target + ".partial"); !os.IsNotExist(err) {
		t.Fatalf("partial left behind (%v)", err)
	}

	// Once: an existing sidecar is refused, and left as it is.
	if r, err := ImportStandby(StandbyOptions{From: archive, DataDir: data}); !errors.Is(err, ErrRefused) || !strings.Contains(r.Refusals[0], "exists") {
		t.Fatalf("a second import: %v %v", err, r.Refusals)
	}
}

// A standby chain that does not verify, or a sessions.json that does not parse, is refused and
// leaves no sidecar; the source is never written.
func TestImportStandbyRefuses(t *testing.T) {
	for name, edit := range map[string]func(archive string){
		"an edited record": func(archive string) {
			p := filepath.Join(archive, "audit", "2026-11.jsonl")
			b := readBytes(t, p)
			if err := os.WriteFile(p, []byte(strings.Replace(string(b), `"operation":"apply"`, `"operation":"stop"`, 1)), 0o600); err != nil { //nolint:gosec // the test's own dir
				t.Fatal(err)
			}
		},
		"a bad sessions.json": func(archive string) {
			if err := os.WriteFile(filepath.Join(archive, "sessions.json"), []byte("{"), 0o600); err != nil { //nolint:gosec // the test's own dir
				t.Fatal(err)
			}
		},
	} {
		t.Run(name, func(t *testing.T) {
			archive, data := standbySetup(t)
			edit(archive)
			before := archiveFingerprint(t, archive)
			r, err := ImportStandby(StandbyOptions{From: archive, DataDir: data})
			if !errors.Is(err, ErrRefused) || r.Result != ResultRefused {
				t.Fatalf("%v %s %v", err, r.Result, r.Refusals)
			}
			if _, err := os.Lstat(filepath.Join(data, "sidecar", "standby")); !os.IsNotExist(err) {
				t.Fatal("a refused import left the sidecar")
			}
			if _, err := os.Lstat(filepath.Join(data, "sidecar", "standby.partial")); !os.IsNotExist(err) {
				t.Fatal("a refused import left the partial copy")
			}
			if archiveFingerprint(t, archive) != before {
				t.Fatal("the import wrote the source")
			}
		})
	}
}
