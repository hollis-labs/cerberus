-- Cerberus schema, class B: telemetry (docs/substrate-port-plan.md, section 5.1). The host-monitoring tables,
-- with the old build's columns (old migrations 006 to 008), so the import copies rows unchanged. SQLite at
-- cutover; they may move to Postgres after acceptance, as one step (host_rollup_state moves with the rollups).
-- When they do, this file moves to that store's migration set.
--
-- Until the first release this file is edited in place; after it, changes go in new numbered files. Times are
-- unix seconds, UTC. The sqlite/ twin of this file must stay equivalent; the store tests run on both.

-- +goose Up
-- One row per successful probe.
CREATE TABLE host_samples (
    host TEXT NOT NULL,
    ts BIGINT NOT NULL,
    load1 DOUBLE PRECISION,
    load5 DOUBLE PRECISION,
    load15 DOUBLE PRECISION,
    cpu BIGINT,
    mem_total BIGINT,
    mem_available BIGINT,
    disk_total BIGINT,
    disk_free BIGINT,
    uptime_s BIGINT,
    probe_ms BIGINT,
    PRIMARY KEY (host, ts)
);

-- Derived health, one row per host.
CREATE TABLE host_status (
    host TEXT PRIMARY KEY,
    status TEXT NOT NULL,
    reasons TEXT NOT NULL DEFAULT '[]',
    since BIGINT NOT NULL,
    last_ok BIGINT,
    last_attempt BIGINT,
    next_due BIGINT,
    consecutive_failures BIGINT NOT NULL DEFAULT 0,
    candidate TEXT NOT NULL DEFAULT '',
    candidate_count BIGINT NOT NULL DEFAULT 0
);

-- One grain-sized bucket (5m, 1h, 1d) of a host's samples: sums, counts and extremes, so
-- coarser grains combine exactly.
CREATE TABLE host_sample_rollups (
    host TEXT NOT NULL,
    grain TEXT NOT NULL,
    bucket_ts BIGINT NOT NULL,
    n BIGINT NOT NULL,
    load1_n BIGINT NOT NULL DEFAULT 0,
    load1_sum DOUBLE PRECISION,
    load1_min DOUBLE PRECISION,
    load1_max DOUBLE PRECISION,
    mem_avail_sum BIGINT,
    mem_avail_min BIGINT,
    mem_avail_max BIGINT,
    disk_free_sum BIGINT,
    disk_free_min BIGINT,
    disk_free_max BIGINT,
    probe_ms_sum BIGINT,
    probe_ms_max BIGINT,
    uptime_max BIGINT,
    cpu_max BIGINT,
    mem_total_max BIGINT,
    disk_total_max BIGINT,
    PRIMARY KEY (host, grain, bucket_ts)
);

-- Per host and grain, the end of the last committed bucket: raw rows (and finer rollups)
-- are deleted only below it.
CREATE TABLE host_rollup_state (
    host TEXT NOT NULL,
    grain TEXT NOT NULL,
    watermark BIGINT NOT NULL,
    PRIMARY KEY (host, grain)
);

-- Append-only status changes, read by id (SSE Last-Event-ID, the MCP poll tool). An identity column,
-- so ids never repeat; an import sets the identity past the highest copied id. Reasons are codes only.
CREATE TABLE host_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts BIGINT NOT NULL,
    host TEXT NOT NULL,
    kind TEXT NOT NULL,
    from_status TEXT NOT NULL,
    to_status TEXT NOT NULL,
    reasons TEXT NOT NULL DEFAULT '[]',
    expected BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX host_events_host ON host_events (host, id);
